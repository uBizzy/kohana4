	/**
	 * Searches for a file in the [Cascading Filesystem](kohana/files), and
	 * returns the path to the file that has the highest precedence, so that it
	 * can be included.
	 *
	 * When searching the "config", "messages", or "i18n" directories, or when
	 * the `$array` flag is set to true, an array of all the files that match
	 * that path in the [Cascading Filesystem](kohana/files) will be returned.
	 * These files will return arrays which must be merged together.
	 *
	 * If no extension is given, the default extension (`EXT` set in
	 * `index.php`) will be used.
	 *
	 *     // Returns an absolute path to views/template.php
	 *     Kohana::find_file('views', 'template');
	 *
	 *     // Returns an absolute path to media/css/style.css
	 *     Kohana::find_file('media', 'css/style', 'css');
	 *
	 *     // Returns an array of all the "mimes" configuration files
	 *     Kohana::find_file('config', 'mimes');
	 *
	 * @param   string  $dir    directory name (views, i18n, classes, extensions, etc.)
	 * @param   string  $file   filename with subdirectory
	 * @param   string  $ext    extension to search for
	 * @param   bool $array  return an array of files?
	 * @return  ($array is true ? array<int, string> : ($dir is 'config'|'i18n'|'messages' ? array<int, string> : string|false))  a list of files when $array is true and for config, i18n and messages
	 */
	public static function find_file(string $dir, string $file, ?string $ext = null, bool $array = false): string|array|false
	{
		// Lists are returned for these directories, a single path for the others
		$as_list = ($array OR $dir === 'config' OR $dir === 'i18n' OR $dir === 'messages');

		// A name must stay inside the directory it is searched in: ".." parts
		// and NUL bytes are refused, so a name built from user input cannot
		// reach files elsewhere on the disk
		if (str_contains($file, "\0") OR preg_match('#(?:^|[/\\\\])\.\.(?:[/\\\\]|$)#', $file))
			return $as_list ? [] : false;

		if ($ext === null)
		{
			// Use the default extension
			$ext = EXT;
		}
		elseif ($ext)
		{
			// Prefix the extension with a period
			$ext = ".{$ext}";
		}
		else
		{
			// Use no extension
			$ext = '';
		}

		// Create a partial path of the filename
		$path = $dir.DIRECTORY_SEPARATOR.$file.$ext;

		if (Kohana::$caching === true AND isset(Kohana::$_files[$path.($array ? '_array' : '_path')]))
		{
			// This path has been cached
			return Kohana::$_files[$path.($array ? '_array' : '_path')];
		}

		if (Kohana::$profiling === true AND class_exists('Profiler', false))
		{
			// Start a new benchmark, named after the file that is looked for
			$benchmark = Profiler::start('Find file', $path);
		}

		if ($as_list)
		{
			// Include paths must be searched in reverse
			$paths = array_reverse(Kohana::$_paths);

			// Array of files that have been found
			$found = [];

			foreach ($paths as $dir)
			{
				if (is_file($dir.$path))
				{
					// This path has a file, add it to the list
					$found[] = $dir.$path;
				}
			}
		}
		else
		{
			// The file has not been found yet
			$found = false;

			foreach (Kohana::$_paths as $dir)
			{
				if (is_file($dir.$path))
				{
					// A path has been found
					$found = $dir.$path;

					// Stop searching
					break;
				}
			}
		}

		if (Kohana::$caching === true)
		{
			// Add the path to the cache
			Kohana::$_files[$path.($array ? '_array' : '_path')] = $found;

			// Files have been changed
			Kohana::$_files_changed = true;
		}

		if (isset($benchmark))
		{
			// Stop the benchmark
			Profiler::stop($benchmark);

			// Where the file was found: the paths, or how many when a list was asked for
			Profiler::note($benchmark, match (true) {
				($found === false OR $found === []) => 'not found',
				is_array($found)                    => implode(', ', $found),
				default                             => $found,
			});
		}

		return $found;
	}

	/**
	 * Recursively finds all of the files in the specified directory at any
	 * location in the [Cascading Filesystem](kohana/files), and returns an
	 * array of all the files found, sorted alphabetically.
	 *
	 *     // Find all view files.
	 *     $views = Kohana::list_files('views');
	 *
	 * @param   string  		$directory   directory name
	 * @param   array<int, string>   		$paths       list of paths to search
	 * @param   string|array<int, string>	$ext		 only list files with this extension
	 * @param   bool			$sort		 sort alphabetically
	 *
	 * @return  array<string, mixed>
	 */
	public static function list_files(?string $directory = null, ?array $paths = null, string|array|null $ext = null, ?bool $sort = null): array
	{
		if ($directory !== null)
		{
			// Add the directory separator
			$directory .= DIRECTORY_SEPARATOR;
		}

		if ($paths === null)
		{
			// Use the default paths
			$paths = Kohana::$_paths;
		}

		if (is_string($ext))
		{
			// convert string extension to array
			$ext = [$ext];
		}

		if ($sort === null)
		{
			// sort results by default
			$sort = true;
		}

		// Create an array for the files
		$found = [];

		foreach ($paths as $path)
		{
			if (is_dir($path.$directory))
			{
				// Create a new directory iterator
				$dir = new DirectoryIterator($path.$directory);

				foreach ($dir as $file)
				{
					// Get the file name
					$filename = $file->getFilename();

					if ($filename[0] === '.' OR $filename[strlen($filename)-1] === '~')
					{
						// Skip all hidden files and UNIX backup files
						continue;
					}

					// Relative filename is the array key
					$key = $directory.$filename;

					if ($file->isDir())
					{
						if ($sub_dir = Kohana::list_files($key, $paths, $ext, $sort))
						{
							if (isset($found[$key]))
							{
								// Append the sub-directory list
								$found[$key] = (array) $found[$key] + $sub_dir;
							}
							else
							{
								// Create a new sub-directory list
								$found[$key] = $sub_dir;
							}
						}
					}
					elseif ($ext === null || in_array('.'.$file->getExtension(), $ext, true))
					{
						if ( ! isset($found[$key]))
						{
							// Add new files to the list
							$found[$key] = realpath($file->getPathname());
						}
					}
				}
			}
		}

		if ($sort)
		{
			// Sort the results alphabetically
			ksort($found);
		}

		return $found;
	}

	/**
	 * Loads a file within a totally empty scope and returns the output:
	 *
	 *     $foo = Kohana::load('foo.php');
	 *
	 * @param   string  $file
	 * @return  mixed
	 */
	public static function load(string $file): mixed
	{
		return include $file;
	}

	/**
	 * Cache variables using current cache module if enabled, if not uses Kohana::file_cache
	 *
	 *     // Set the "foo" cache
	 *     Kohana::cache('foo', 'hello, world');
	 *
	 *     // Get the "foo" cache
	 *     $foo = Kohana::cache('foo');
	 *
	 * @throws  Kohana_Exception
	 * @param   string  $name       name of the cache
	 * @param   mixed   $data       data to cache
	 * @param   int $lifetime   number of seconds the cache is valid for
	 * @return  mixed    for getting
	 */
	public static function cache(string $name, mixed $data = null, ?int $lifetime = null): mixed
	{
		if ( ! Kohana::_has_cache_module())
		{
			// No Cache module, or it has no configuration: use the internal file cache
			return Kohana::file_cache($name, $data, $lifetime);
		}

		if ($lifetime === 0)
		{
			// Delete the cache
			return Cache::instance()->delete($name);
		}

		if ($data === null)
		{
			// No data given: read the cache
			return Cache::instance()->get($name);
		}

		// Save the data
		return Cache::instance()->set($name, $data, $lifetime);
	}

	/**
	 * Tells whether the Cache module can be used by [Kohana::cache]: it
	 * must be loaded, and its default group must be in the "cache"
	 * configuration. The answer is kept for the rest of the request.
	 *
	 * @return  bool
	 */
	protected static function _has_cache_module(): bool
	{
		/** @var bool|null $usable */
		static $usable = null;

		if ($usable === null)
		{
			// The module can only be asked once the configuration is ready (not while the framework starts)
			if ( ! class_exists('Kohana_Cache') OR Kohana::$config === null)
				return false;

			$usable = (isset(Cache::$instances[Cache::$default])
				OR (($config = Kohana::$config->load('cache')) instanceof Config_Group AND $config->offsetExists(Cache::$default)));
		}

		return $usable;
	}

	/**
	 * Provides simple file-based caching for strings and arrays:
	 *
	 *     // Set the "foo" cache
	 *     Kohana::file_cache('foo', 'hello, world');
	 *
	 *     // Get the "foo" cache
	 *     $foo = Kohana::file_cache('foo');
	 *
	 * All caches are stored as PHP code, generated with [var_export][ref-var].
	 * Caching objects may not work as expected. Storing references or an
	 * object or array that has recursion will cause an E_FATAL.
	 *
	 * The cache directory and default cache lifetime is set by [Kohana::init]
	 *
	 * [ref-var]: http://php.net/var_export
	 *
	 * @throws  Kohana_Exception
	 * @param   string  $name       name of the cache
	 * @param   mixed   $data       data to cache
	 * @param   int $lifetime   number of seconds the cache is valid for
	 * @return  mixed    for getting
	 */
	public static function file_cache(string $name, mixed $data = null, ?int $lifetime = null): mixed
	{
		// Cache file is a hash of the name
		$file = hash('sha256', $name).'.txt';

		// Cache directories are split by keys to prevent filesystem overload
		$dir = Kohana::$cache_dir.DIRECTORY_SEPARATOR.$file[0].$file[1].DIRECTORY_SEPARATOR;

		if ($lifetime === null)
		{
			// Use the default lifetime
			$lifetime = Kohana::$cache_life;
		}

		if ($data === null)
		{
			if (is_file($dir.$file))
			{
				if ((time() - filemtime($dir.$file)) < $lifetime)
				{
					// Return the cache
					$serialized = (string) @file_get_contents($dir.$file);
					$cached = @unserialize($serialized);

					if ($cached !== false OR $serialized === 'b:0;')
					{
						// Return the cache
						return $cached;
					}

					// Cache is corrupt, let return happen normally.
				}
				else
				{
					try
					{
						// Cache has expired
						unlink($dir.$file);
					}
					catch (Throwable $e)
					{
						// Cache has mostly likely already been deleted,
						// let return happen normally.
					}
				}
			}

			// Cache not found
			return null;
		}

		if ( ! is_dir($dir))
		{
			// Create the cache directory
			mkdir($dir, 0775, true);

			// Set permissions (must be manually set to fix umask issues)
			chmod($dir, 0775);
		}

		// Force the data to be a string
		$data = serialize($data);

		try
		{
			// Write the cache
			return (bool) file_put_contents($dir.$file, $data, LOCK_EX);
		}
		catch (Throwable $e)
		{
			// Failed to write cache
			return false;
		}
	}

	/**
	 * Get a message from a file. Messages are arbitrary strings that are stored
	 * in the `messages/` directory and reference by a key. Translation is not
	 * performed on the returned values.  See [message files](kohana/files/messages)
	 * for more information.
	 *
	 *     // Get "username" from messages/text.php
	 *     $username = Kohana::message('text', 'username');
	 *
	 * @param   string  $file       file name
	 * @param   string  $path       key path to get
	 * @param   mixed   $default    default value if the path does not exist
	 * @return  mixed   the message for the given path (a text, or an array of messages), or the default
	 * @uses    Arr::merge
	 * @uses    Arr::path
	 */
	public static function message(string $file, ?string $path = null, mixed $default = null): mixed
	{
		/** @var array<string, array<int|string, mixed>> $messages */
		static $messages = [];

		if ( ! isset($messages[$file]))
		{
			// Create a new message list
			$messages[$file] = [];

			if ($files = Kohana::find_file('messages', $file))
			{
				foreach ($files as $f)
				{
					// Combine all the messages recursively
					$messages[$file] = Arr::merge($messages[$file], (array) Kohana::load($f));
				}
			}
		}

		if ($path === null)
		{
			// Return all of the messages
			return $messages[$file];
		}
		else
		{
			// Get a message using the path
			return Arr::path($messages[$file], $path, $default);
		}
	}

	/**
	 * PHP error handler, converts all errors into Error_Exceptions. This handler
	 * respects error_reporting settings.
	 *
	 * @throws  Error_Exception
	 * @return  true
	 */
	public static function error_handler(int $code, string $error, ?string $file = null, ?int $line = null): bool
	{
		if ( ! (error_reporting() & $code))
		{
			// This error is not in the error_reporting setting: ignore it
			return true;
		}

		if (in_array($code, Kohana::$soft_errors, true))
		{
			// Record it and let the request continue
			Kohana::_soft_error($code, $error, (string) $file, (int) $line);

			return true;
		}

		// Convert the error into an exception: the request stops here
		throw new Error_Exception($error, null, $code, 0, $file ?? 'unknown', $line ?? 0);
	}

	/**
	 * Records an error that does not stop the request (see
	 * [Kohana::$soft_errors]): it is written to the log and, outside
	 * production, kept in [Kohana::$notices] for the panel at the bottom
	 * of the page. The same error on the same line is recorded once per request.
	 *
	 * @param   int     $code   PHP error code
	 * @param   string  $error  error message
	 * @param   string  $file   file the error happened in
	 * @param   int     $line   line the error happened on
	 * @return  void
	 */
	protected static function _soft_error(int $code, string $error, string $file, int $line): void
	{
		// Errors already recorded in this request
		/** @var array<string, bool> $seen */
		static $seen = [];

		$key = $code.'|'.$file.'|'.$line.'|'.$error;

		if (isset($seen[$key]))
			return;

		$seen[$key] = true;

		$name = Kohana_Exception::$php_errors[$code] ?? 'Error '.$code;

		if (is_object(Kohana::$log))
		{
			Kohana::$log->add(Log::NOTICE, $name.': '.$error.' ~ '.Debug::path($file).' [ '.$line.' ]');
		}

		if (Kohana::$environment !== Kohana::PRODUCTION)
		{
			Kohana::$notices[] = ['code' => $name, 'message' => $error, 'file' => $file, 'line' => $line];
		}
	}

	/**
	 * Catches errors that are not caught by the error handler, such as E_PARSE.
	 *
	 * @uses    Kohana_Exception::handler
	 * @return  void
	 */
	public static function shutdown_handler(): void
	{
		if ( ! Kohana::$_init)
		{
			// Do not execute when not active
			return;
		}

		try
		{
			if (Kohana::$caching === true AND Kohana::$_files_changed === true)
			{
				// Write the file path cache
				Kohana::cache('Kohana::find_file()', Kohana::$_files);
			}
		}
		catch (Throwable $e)
		{
			// Pass the exception to the handler
			Kohana_Exception::handler($e);
		}

		// Requests that took too long are written to the log
		Profiler::log_slow_request();

		if (Kohana::$notices AND Kohana::$show_notices)
		{
			// Show the deprecation notices of this request (never in production)
			Kohana::_show_notices();
		}

		if (Kohana::$errors AND $error = error_get_last() AND in_array($error['type'], Kohana::$shutdown_errors))
		{
			// Clean the output buffer
			ob_get_level() AND ob_clean();

			// Fake an exception for nice debugging. The handler shows the
			// error and ends the request itself, with an error status.
			Kohana_Exception::handler(new Error_Exception($error['message'], null, $error['type'], 0, $error['file'], $error['line']));
		}
	}

	/**
	 * Prints the panel that lists the notices of this request, at the end
	 * of an HTML page. Nothing is printed on the command line, for AJAX
	 * requests, or when the response is not HTML (JSON, a download, ...),
	 * where extra output would break the response.
	 *
	 * @return  void
	 */
	protected static function _show_notices(): void
	{
		if (PHP_SAPI === 'cli' OR Kohana::$environment === Kohana::PRODUCTION)
			return;

		$with = $_SERVER['HTTP_X_REQUESTED_WITH'] ?? null;

		if (is_string($with) AND strtolower($with) === 'xmlhttprequest')
			return;

		foreach (headers_list() as $header)
		{
			// A response that says it is something other than HTML is left alone
			if (stripos($header, 'content-type:') === 0 AND stripos($header, 'text/html') === false)
				return;
		}

		try
		{
			echo View::factory('kohana/notices', ['notices' => Kohana::$notices])->render();
		}
		catch (Throwable $e)
		{
			// The panel is a help for the developer: it must never break the page
		}
	}

